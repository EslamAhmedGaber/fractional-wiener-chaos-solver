"""Generate LaTeX macros (source/tables/numbers_p1.tex) and worked example table (source/tables/t4_worked.tex)
for Problem 1 from evidence/P1_malthusian/p1_results.json."""
import json
import math
import os
import numpy as np
from style import EVID, ROOT

P1 = os.path.join(EVID, 'P1_malthusian')
R = json.load(open(os.path.join(P1, 'p1_results.json')))
TAB = os.path.join(ROOT, 'source', 'tables')
os.makedirs(TAB, exist_ok=True)


def f(x, d=3):
    return f'{x:.{d}f}'


def sig(x, n=2):
    if x == 0 or not np.isfinite(x):
        return '0'
    d = max(0, n - 1 - int(math.floor(math.log10(abs(x)))))
    return f'{x:.{d}f}'


def sci(x):
    s = f'{x:.1e}'
    mant, exp = s.split('e')
    exp_i = int(exp)
    if mant.endswith('.0'):
        mant = mant[:-2]
    return rf'{mant}\times10^{{{exp_i}}}'


macros = {}
wk = R['worked']
G = np.array(wk['G'])
Lm = np.array(wk['L'])
macros.update(
    WkMpiRe=f(wk['M_pi'][0], 6), WkMpiIm=f(wk['M_pi'][1], 6),
    WkMtwopiRe=f(wk['M_2pi'][0], 6), WkMtwopiIm=f(wk['M_2pi'][1], 6),
    WkGzz=f(G[0, 0], 6), WkGoo=f(G[1, 1], 6), WkGtt=f(G[2, 2], 6), WkGzt=f(G[0, 2], 6),
    WkMpDiff=sci(wk['mpmath_max_diff']),
)
r1, r2 = wk['rows']
macros.update(
    WkqJmid=f(r1['qJ'], 6), Wkqmid=f(r1['q'], 6), WkqJend=f(r2['qJ'], 6),
    WkModeErrPct=sig(100.0 * abs(r1['qJ'] / r1['q'] - 1.0), 2),
    WkDegErrOne=f(r2['exact'] - r2['cos_p1'], 3),
    WkDegErrFive=sci(r2['exact'] - r2['cos_p5']),
)

# Condition numbers at J = 257 (Corollary 4)
def cond_row(H, J):
    return next(r for r in R['condition'] if abs(r['H'] - H) < 1e-9 and r['J'] == J)

macros.update(
    CondLow=f(cond_row(0.55, 257)['cond2'], 1),
    CondMid=f(cond_row(0.75, 257)['cond2'], 1),
    CondHigh=f(cond_row(0.95, 257)['cond2'], 0),
    CholResMax=sci(max(r['chol_rel_res'] for r in R['condition'])),
)

# Terminal identity with analytic FWHE & general solver check
idd = [r['terminal_equals_fwhe'] for r in R['identity'] if r['method'] == 'CosChaos']
macros['IdentityMaxDiff'] = sci(max(idd))
macros['GeneralSolverCheck'] = sci(max(c['max_rel_diff_to_closed_form'] for c in R['check']))

# Fig. 2(a) numbers at H = 0.75, p = 5
id_fw75 = next(r for r in R['identity'] if r['method'] == 'FWHE analytic' and abs(r['H'] - 0.75) < 1e-9 and r['p'] == 5)
id_cc75 = next(r for r in R['identity'] if r['method'] == 'CosChaos' and abs(r['H'] - 0.75) < 1e-9 and r['J'] == 17 and r['p'] == 5)
macros['IdFwheMidErr'] = sig(id_fw75['max_abs_err'], 2)
macros['IdCcMidErr'] = sig(id_cc75['max_abs_err'], 2)

# FWHE-GL vs accelerated CosChaos at H = 0.95
def gl_row(H, m, key, val):
    return next(r for r in R['fwhegl'] if abs(r['H'] - H) < 1e-9 and r['method'] == m and r.get(key) == val)

cc17 = gl_row(0.95, 'CosChaos', 'J', 17)
gl25 = gl_row(0.95, 'FWHE-GL', 'N', 25600)
macros.update(
    GLccErr=sig(cc17['max_abs_err'], 2),
    GLccSec=sig(cc17['seconds'], 2),
    GLglErr=sig(gl25['max_abs_err'], 2),
    GLglSec=sig(gl25['seconds'], 2),
    GLSpeedup=f(gl25['seconds'] / cc17['seconds'], 0),
)

# Discrete Wick (BP) vs CosChaos
W = R['discrete_wick']['rows']
def w_row(H, m, **kw):
    return next(r for r in W if abs(r['H'] - H) < 1e-9 and r['method'].startswith(m) and all(r.get(k) == v for k, v in kw.items()))

macros.update(
    BPstrong=f(w_row(0.95, 'BP', n=16384)['max_var_err'], 1),
    CCstrong=sig(w_row(0.95, 'CosChaos', J=5, p=5)['max_var_err'], 2),
    CCstrongTime=sig(w_row(0.95, 'CosChaos', J=5, p=5)['general_solver_s'], 2),
    BPweak=sig(w_row(0.55, 'BP', n=64)['max_var_err'], 2),
    BPweakTime=sig(w_row(0.55, 'BP', n=64)['seconds'], 2),
    CCweak=sig(w_row(0.55, 'CosChaos', J=65, p=7)['max_var_err'], 2),
)
lo95 = next(r for r in R['discrete_wick']['loss'] if abs(r['H'] - 0.95) < 1e-9)
macros['LossCell'] = f(100.0 * lo95['first_cell_share_of_driver_loss'], 1)

# H-free sweep
sw = R['h_sweep']
sw_errs = [r['max_rel_err'] for r in sw['rows']]
macros.update(
    SweepMaxErr=sig(max(sw_errs), 2),
    SweepSetup=sig(sw['setup_s'], 2),
    SweepQuery=sig(sw['query_s'], 2),
    SweepTotal=sig(sw['setup_s'] + sw['query_s'], 2),
    SweepErrHigh=sig(sw_errs[-1], 2),
)

with open(os.path.join(TAB, 'numbers_p1.tex'), 'w', encoding='utf-8') as fh:
    fh.write('% Generated by scripts/make_p1_tables.py from evidence/P1_malthusian/p1_results.json\n')
    for k, v in macros.items():
        fh.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')

# Worked example table
lines = [
    r'\begin{widetable}\centering\small',
    r"\caption{Worked example for Problem~1 ($H=0.75$, $T=2$, $\mu=0.2$, $\sigma=0.5$, $J=3$), recomputable by hand from the two values of $M_H$ in Section~\ref{sec:gram}. Variances come from the coefficients; ``exact'' is the lognormal variance.}\label{tab:worked}",
    r'\begin{tabular}{@{}llL{0.54\linewidth}@{}}\toprule',
    r'Step & Source & Value\\\midrule',
    r'Gram matrix & Prop.~\ref{prop:gram} & $G_{00}=' + f(G[0, 0], 6) + r'$, $G_{11}=' + f(G[1, 1], 6) + r'$, $G_{22}=' + f(G[2, 2], 6) + r'$, $G_{02}=' + f(G[0, 2], 6) + r'$\\',
    r'Cholesky factor & Eq.~\eqref{eq:buildmodes} & $L_{00}=' + f(Lm[0, 0], 6) + r'$, $L_{11}=' + f(Lm[1, 1], 6) + r'$, $L_{20}=' + f(Lm[2, 0], 6) + r'$, $L_{22}=' + f(Lm[2, 2], 6) + r'$\\',
    r'Vector $b$ at $t=1$ & $b=\sigma L^\top m(1)$ & $b=(' + ', '.join(f(x, 6) for x in r1['b']) + r')$, $q_J=|b|^2=' + f(r1['qJ'], 6) + r'$ (exact $' + f(r1['q'], 6) + r'$)\\',
    r'Vector $b$ at $t=T$ & Prop.~\ref{prop:noise} & $b=(' + ', '.join(f(abs(x), 6) for x in r2['b']) + r')$, $q_J=' + f(r2['qJ'], 6) + r'=\sigma^2T^{2H}$\\\bottomrule',
    r'\end{tabular}',
    r'\par\medskip',
    r'\begin{tabular}{@{}llrrrr@{}}\toprule',
    r'Variance & Source & $p=1$ & $p=3$ & $p=5$ & exact\\\midrule',
]
for r, lab in ((r1, 't=1'), (r2, 't=T=2')):
    lines.append(rf'\CC{{}}, ${lab}$ & Prop.~\ref{{prop:malthus}}(b) & ' + ' & '.join(f(r[f'cos_p{p}'], 6) for p in (1, 3, 5)) + ' & ' + f(r['exact'], 6) + r'\\')
    lines.append(rf'FWHE order $p$, ${lab}$ & \cite[Eq.~(55)]{{EEM22}} & ' + ' & '.join(f(r[f'fwhe_p{p}'], 6) for p in (1, 3, 5)) + ' & ' + f(r['exact'], 6) + r'\\')
lines += [r'\bottomrule\end{tabular}', r'\end{widetable}']

open(os.path.join(TAB, 't4_worked.tex'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('numbers_p1.tex and t4_worked.tex written;', len(macros), 'macros')
