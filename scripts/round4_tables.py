"""Round 4 numbers: Gaussian (mean-variance) law against the exact Wick growth law, and the event probability
P(X(4) > c) of the cubic single well (evidence/round4/P4_cubic_event.json, scripts/round4_probability.py).
Writes source/tables/round4_numbers.tex (macros used in the text), supplement/source/tables/tab_cubicevent.tex
and evidence/round4/derived_numbers_4.json.  Run from working/:  python scripts/round4_tables.py
"""
import json, math, os
import numpy as np
from scipy import stats
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
E4 = os.path.join(ROOT, 'evidence', 'round4'); P4 = json.load(open(os.path.join(E4, 'P4_cubic_event.json')))
P2 = json.load(open(os.path.join(ROOT, 'evidence', 'round3_full', 'P2_wick_law.json')))
HS = ['0.55', '0.75', '0.95']; NAME = {'0.55': 'FF', '0.75': 'SF', '0.95': 'NF'}


def wick_gauss(H, t=2.0, mu=0.2, s=0.5, x0=1.0):
    v = s ** 2 * t ** (2 * H); m = x0 * math.exp(mu * t); var = m ** 2 * math.expm1(v); sd = math.sqrt(var)
    ex = lambda q: m * math.exp(math.sqrt(v) * stats.norm.ppf(q) - v / 2); ga = lambda q: m + sd * stats.norm.ppf(q)
    return dict(mean=m, var=var, exact_q99=ex(.99), exact_q01=ex(.01), gauss_q99=ga(.99), gauss_q01=ga(.01),
                gauss_q99_relerr=ga(.99) / ex(.99) - 1, gauss_mass_below_zero=float(stats.norm.cdf(-m / sd)),
                coschaos_q99_relerr_p5=P2[str(H)]['2.0']['65,5']['q99'], coschaos_q99_relerr_p3=P2[str(H)]['2.0']['65,3']['q99'])


W = {H: wick_gauss(float(H)) for H in HS}
lev = np.array(P4['meta']['levels']); it = P4['meta']['times'].index(4.0); C = 0.7; k = int(np.argmin(abs(lev - C)))
EV = {}
for H in HS:
    r = P4[H]; mu, var = r['mc_512']['mean'][it], r['mc_512']['var'][it]
    EV[H] = dict(mc=r['mc_512']['p'][it][k], mc_ci=r['mc_512']['ci'][it][k], mc256=r['mc_256']['p'][it][k], mc256_ci=r['mc_256']['ci'][it][k],
                 cc95=r['chaos_9,5']['p'][it][k], cc173=r['chaos_17,3']['p'][it][k], gauss=float(stats.norm.sf((C - mu) / math.sqrt(var))),
                 mc_var=var, cc95_var=r['chaos_9,5']['var'][it], seconds_cc95=r['chaos_9,5']['seconds_solve'] + r['chaos_9,5']['seconds_eval'],
                 seconds_mc=r['mc_512']['seconds'])
    EV[H]['cc95_dev'] = EV[H]['cc95'] / EV[H]['mc'] - 1; EV[H]['gauss_dev'] = EV[H]['gauss'] / EV[H]['mc'] - 1
# validity band of degree five: largest deviation over c in [0.4, 0.75]
band = [i for i, c in enumerate(lev) if 0.4 - 1e-9 <= c <= 0.75 + 1e-9]
dev_band = max(abs(P4[H]['chaos_9,5']['p'][it][i] / P4[H]['mc_512']['p'][it][i] - 1) for H in HS for i in band)
dev08 = P4['0.95']['chaos_9,5']['p'][it][int(np.argmin(abs(lev - 0.8)))] / P4['0.95']['mc_512']['p'][it][int(np.argmin(abs(lev - 0.8)))] - 1
f1 = lambda x, d=1: f'{x:.{d}f}'
mac = {
 'GaussMean': f1(W['0.75']['mean'], 2), 'GaussVar': f1(W['0.75']['var'], 2), 'GaussQnn': f1(W['0.75']['gauss_q99'], 2),
 'ExactQnn': f1(W['0.75']['exact_q99'], 2), 'GaussQnnErr': f'{-100 * W["0.75"]["gauss_q99_relerr"]:.0f}',
 'GaussQone': f'$-${-W["0.75"]["gauss_q01"]:.2f}'.replace('$-$', '-'), 'ExactQone': f1(W['0.75']['exact_q01'], 3),
 'CCQnnPfive': f1(100 * W['0.75']['coschaos_q99_relerr_p5'], 2), 'GaussNegMass': f'{100 * W["0.75"]["gauss_mass_below_zero"]:.0f}',
 'GaussQnnErrLow': f'{-100 * max(W[H]["gauss_q99_relerr"] for H in HS):.0f}', 'GaussQnnErrHigh': f'{-100 * min(W[H]["gauss_q99_relerr"] for H in HS):.0f}',
 'GaussNegLow': f'{100 * min(W[H]["gauss_mass_below_zero"] for H in HS):.0f}', 'GaussNegHigh': f'{100 * max(W[H]["gauss_mass_below_zero"] for H in HS):.0f}',
 'EvLevel': f1(C, 1), 'EvCCMaxDev': f1(100 * max(abs(EV[H]['cc95_dev']) for H in HS), 1),
 'EvGaLow': f'{100 * min(EV[H]["gauss_dev"] for H in HS):.0f}', 'EvGaHigh': f'{100 * max(EV[H]["gauss_dev"] for H in HS):.0f}',
 'EvVarRise': f'{100 * (EV["0.95"]["mc_var"] / EV["0.55"]["mc_var"] - 1):.0f}', 'EvMCRise': f'{100 * (EV["0.95"]["mc"] / EV["0.55"]["mc"] - 1):.0f}',
 'EvBandDev': f1(100 * dev_band, 1), 'EvDevEightNF': f'{-100 * dev08:.0f}',
 'EvBandPmin': f1(100 * min(P4[H]['mc_512']['p'][it][band[-1]] for H in HS), 2),
 'EvStepDev': f1(max(abs(EV[H]['mc'] - EV[H]['mc256']) / math.hypot(EV[H]['mc_ci'], EV[H]['mc256_ci']) for H in HS), 1),
 'EvCCRise': f'{100 * (EV["0.95"]["cc95"] / EV["0.55"]["cc95"] - 1):.0f}',
}
for H in HS:
    n = NAME[H]; e = EV[H]
    mac.update({f'EvMC{n}': f1(100 * e['mc'], 2), f'EvMCci{n}': f1(100 * e['mc_ci'], 2), f'EvCC{n}': f1(100 * e['cc95'], 2),
                f'EvCCdev{n}': f'{100 * e["cc95_dev"]:+.1f}', f'EvGa{n}': f1(100 * e['gauss'], 2), f'EvGadev{n}': f'{100 * e["gauss_dev"]:+.0f}'})
mac['GaussQone'] = '-' + f1(-W['0.75']['gauss_q01'], 2)
open(os.path.join(ROOT, 'source', 'tables', 'round4_numbers.tex'), 'w', encoding='utf-8').write(
    '% generated by scripts/round4_tables.py\n' + ''.join(f'\\newcommand{{\\{a}}}{{{b}}}\n' for a, b in mac.items()))
# supplementary table: P(X(4) > c) in percent
rows = []; cs = [0.5, 0.6, 0.7, 0.75, 0.8, 0.85]
for H in HS:
    r = P4[H]; mu, var = r['mc_512']['mean'][it], r['mc_512']['var'][it]
    for j, c in enumerate(cs):
        i = int(np.argmin(abs(lev - c))); mc = r['mc_512']['p'][it][i]
        cell = lambda x: f'{100 * x:.3f}'
        rows.append(f"{H if j == 0 else ''} & {c:.2f} & {cell(mc)} $\\pm$ {100 * r['mc_512']['ci'][it][i]:.3f} & {cell(r['mc_256']['p'][it][i])} & "
                    f"{cell(r['chaos_17,3']['p'][it][i])} & {cell(r['chaos_9,5']['p'][it][i])} & {cell(stats.norm.sf((c - mu) / math.sqrt(var)))}\\\\")
    rows[-1] += '\\addlinespace' if H != HS[-1] else ''
tab = ('\\begin{tabular}{rrccccc}\\toprule\n $H$ & $c$ & Monte Carlo, $512$ steps & Monte Carlo, $256$ & CosChaos, $J=17$, $p=3$ & CosChaos, $J=9$, $p=5$ & Gaussian\\\\\\midrule\n'
       + '\n'.join(rows) + '\n\\bottomrule\\end{tabular}\n')
open(os.path.join(ROOT, 'supplement', 'source', 'tables', 'tab_cubicevent.tex'), 'w', encoding='utf-8').write(tab)
json.dump(dict(wick_gauss=W, event_level=C, event=EV, dev_band_c_0p4_0p75=dev_band, dev_c0p8_H095_p5=dev08, macros=mac),
          open(os.path.join(E4, 'derived_numbers_4.json'), 'w'), indent=1)
print(json.dumps(mac, indent=0))
