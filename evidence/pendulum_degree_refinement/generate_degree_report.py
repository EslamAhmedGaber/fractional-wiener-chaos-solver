"""Summarize the complete degree experiment; all numerical manuscript additions are generated."""
from pathlib import Path
import json,csv,math,numpy as np
P=Path(__file__).resolve().parent;V=P.parents[1]
runs={}
for f in sorted(P.glob("*.json")):
 d=json.loads(f.read_text())
 if isinstance(d,dict) and "runs" in d:runs.update(d["runs"])
best="J3_p8_q65_lean_rtol1e-09"
assert best in runs,"Final q=15 check has not completed"
full=json.loads((P.parent/"pendulum_refinement/pendulum_refinement.json").read_text())
finite=json.loads((P/"finite_mode_mc_2000.json").read_text())
selected=["J3_p1_q20","J3_p2_q11","J3_p4_q65_lean_rtol1e-09",
          "J3_p6_q65_lean_rtol1e-09",best]
refq=full["variances"][-1][-1][0]
rows=[]
for key in selected:
 r=runs[key];vf=finite["results"][str(r["J"])]["variance"][-1][0]
 rows.append(dict(case=key,J=r["J"],p=r["p"],q=r["quadrature_order"],variance=r["variance"][-1][0],
                  error_full=100*(r["variance"][-1][0]/refq-1),error_same_J=100*(r["variance"][-1][0]/vf-1),
                  seconds=r["seconds"],nodes=r.get("nodes")))
r=runs[best];q13=runs["J3_p8_q55_lean_rtol1e-09"]
changes=100*(np.array(r["variance"])/np.array(q13["variance"])-1)
mchanges=np.array(r["mean"])-np.array(q13["mean"])
fref=finite["results"]["3"]
fullerr=100*(np.array(r["variance"])/np.array(full["variances"][-1])-1)
sameerr=100*(np.array(r["variance"])/np.array(fref["variance"])-1)
zmean=(np.array(r["mean"])-np.array(fref["mean"]))/np.array(fref["se_mean"])
zvar=(np.array(r["variance"])-np.array(fref["variance"]))/np.array(fref["se_variance"])
diag=dict(selected=rows,quadrature_change_55_to_65_percent=changes.tolist(),
          quadrature_mean_change_55_to_65=mchanges.tolist(),best_full_variance_errors_percent=fullerr.tolist(),
          best_finite_J_variance_errors_percent=sameerr.tolist(),best_finite_J_mean_z=zmean.tolist(),
          best_finite_J_variance_z=zvar.tolist(),full_reference_variance_Q10=refq,
          finite_references={j:{k:v[-1] for k,v in finite["results"][j].items()} for j in ["3","5","65"]})
(P/"final_diagnostics.json").write_text(json.dumps(diag,indent=2),encoding="utf-8",newline="\n")
def up(x,digits=2):return math.ceil(abs(x)*10**digits)/10**digits
macros={"PendDegreeVar":f"{r['variance'][-1][0]:.3f}",
"PendDegreeError":f"{abs(fullerr[-1,0]):.1f}","PendDegreeOriginalError":f"{abs(rows[0]['error_full']):.1f}",
"PendDegreeQuadQChange":f"{up(changes[-1,0],3):.3f}","PendDegreeQuadVChange":f"{up(changes[-1,1],3):.3f}",
"PendDegreeMaxQuadChange":f"{up(np.max(abs(changes))):.2f}","PendDegreeVelocityMidError":f"{abs(fullerr[1,1]):.1f}",
"PendDegreeSeconds":f"{r['seconds']:.0f}","PendDegreeMCThree":f"{finite['results']['3']['variance'][-1][0]:.3f}",
"PendDegreeMCFive":f"{finite['results']['5']['variance'][-1][0]:.3f}",
"PendDegreeMCThreeSE":f"{finite['results']['3']['se_variance'][-1][0]:.3f}",
"PendDegreeMCFiveSE":f"{finite['results']['5']['se_variance'][-1][0]:.3f}"}
text="% Generated by evidence/pendulum_degree_refinement/generate_degree_report.py\n"
text+="".join("\\newcommand{\\"+k+"}{"+v+"}\n" for k,v in macros.items())
(P/"degree_macros.tex").write_text(text,encoding="utf-8",newline="\n")
table=r"""\begin{tabular}{rrrrrrr}\toprule
$J$ & $p$ & $q$ & $\Var Q_{J,p}(10)$ & error/full (\%) & error/same $J$ (\%) & time (s)\\\midrule
"""
for x in rows:
 table+=f"{x['J']} & {x['p']} & {x['q']} & {x['variance']:.6f} & ${x['error_full']:+.2f}$ & ${x['error_same_J']:+.2f}$ & {x['seconds']:.1f}"+r"\\"+"\n"
table+=r"\bottomrule\end{tabular}"+"\n"
(P/"tab_pendulum_degree.tex").write_text(table,encoding="utf-8",newline="\n")
print(json.dumps(dict(macros=macros,mean_z=zmean.tolist(),variance_z=zvar.tolist()),indent=2))

# Additional tables and provenance for the isolated degree experiment.
macros.update({
 "PendDegreeVelocityEndError":f"{abs(fullerr[-1,1]):.1f}",
 "PendDegreeMeanQZ":f"{abs(zmean[-1,0]):.2f}",
 "PendDegreeMeanVZ":f"{abs(zmean[-1,1]):.2f}",
 "PendDegreeMaxMeanChange":f"{up(np.max(abs(mchanges)),6):.6f}",
 "PendDegreeMinutes":f"{r['seconds']/60:.1f}",
 "PendDegreeSameJError":f"{abs(sameerr[-1,0]):.1f}",
 "PendDegreeSameJZ":f"{abs(zvar[-1,0]):.2f}",
 "PendDegreeNodes":f"{r['nodes']:,}".replace(",",r"\,"),
 "PendDegreeCoeffs":str(r["coefficients_per_component"]),
 "PendDegreeMCFullSE":f"{full['variance_se'][-1][-1][0]:.3f}"})
bad=runs["J5_p6_q15_lean_rtol1e-09"];badprev=runs["J5_p6_q13_lean_rtol1e-09"]
badchange=100*(np.array(bad["variance"])/np.array(badprev["variance"])-1)
macros["PendDegreeFailedQuad"]=f"{abs(badchange[-1,0]):.1f}"
diag["J5_p6_quadrature_change_13_to_15_percent"]=badchange.tolist()
(P/"final_diagnostics.json").write_text(json.dumps(diag,indent=2),encoding="utf-8",newline="\n")
text="% Generated; do not edit numerical entries.\n"
text+="".join("\\newcommand{\\"+k+"}{"+val+"}\n" for k,val in macros.items())
table=r"""\begin{tabular}{rrrrrr}\toprule
$p$ & $q$ & $\Var Q_{3,p}(10)$ & full (\%) & same $J$ (\%) & time (s)\\\midrule
"""
for x in rows:
 table+=f"{x['p']} & {x['q']} & {x['variance']:.6f} & ${x['error_full']:+.2f}$ & ${x['error_same_J']:+.2f}$ & {x['seconds']:.1f}"+r"\\"+"\n"
table+=r"\bottomrule\end{tabular}"+"\n"
quad=r"""\begin{tabular}{rrrrrrr}\toprule
$J$ & $p$ & $q$ & $\E Q(10)$ & $\E V(10)$ & $\Var Q(10)$ & $\Var V(10)$\\\midrule
"""
for key in ["J3_p8_q45_lean","J3_p8_q55_lean_rtol1e-09",best,
            "J5_p6_q11_lean_rtol1e-09","J5_p6_q13_lean_rtol1e-09","J5_p6_q15_lean_rtol1e-09"]:
 x=runs[key]; vals=x["mean"][-1]+x["variance"][-1]
 quad+=f"{x['J']} & {x['p']} & {x['quadrature_order']} & "+" & ".join((chr(36)+f"{y:.6f}"+chr(36)) for y in vals)+r"\\"+"\n"
quad+=r"\bottomrule\end{tabular}"+"\n"
mom=r"""\begin{tabular}{rlrrrrrr}\toprule
$t$ & state & solver mean & same-$J$ MC & solver var. & same-$J$ MC & s.e. & full MC\\\midrule
"""
for k,t in enumerate(full["times"]):
 for dim,state in enumerate(["Q","V"]):
  vals=[r["mean"][k][dim],fref["mean"][k][dim],r["variance"][k][dim],
        fref["variance"][k][dim],fref["se_variance"][k][dim],full["variances"][-1][k][dim]]
  mom+=f"{t:g} & "+state+" & "+" & ".join((chr(36)+f"{y:.6f}"+chr(36)) for y in vals)+r"\\"+"\n"
mom+=r"\bottomrule\end{tabular}"+"\n"
files={"degree_macros.tex":text,"tab_pendulum_degree.tex":table,
       "tab_pendulum_quadrature.tex":quad,"tab_pendulum_all_moments.tex":mom}
public=(V/"reference_tables").is_dir()
main=V/("reference_tables/main" if public else "source/tables")
sup=V/("reference_tables/supplement" if public else "supplement/source/tables")
for name,value in files.items():
 (P/name).write_text(value,encoding="utf-8",newline="\n")
 (sup/name).write_text(value,encoding="utf-8",newline="\n")
 if name in ["degree_macros.tex","tab_pendulum_degree.tex"]:(main/name).write_text(value,encoding="utf-8",newline="\n")
print(json.dumps(macros,indent=2))


